#!/usr/bin/env python3
"""Regenerates app/src/main/java/com/abyssal/files/MolangData.kt from Microsoft's Molang reference.

Sources:
- https://github.com/MicrosoftDocs/minecraft-creator: QueryFunctions.md, MathFunctions.md and the per-query pages
  (descriptions, and the arguments when a sample shows them)
- https://github.com/Blockception/BC-Minecraft-Molang (BSD-3-Clause, Copyright (c) 2021, Blockception Ltd): parameter
  names and deprecations from src/data/general.ts
Run from the repo root:  python3 tools/gen_molang.py
"""
import concurrent.futures, json, os, re, urllib.request

BASE = ("https://raw.githubusercontent.com/MicrosoftDocs/minecraft-creator/main/"
        "creator/Reference/Content/MolangReference/Examples/MolangConcepts/")
OUT = os.path.join(os.path.dirname(__file__), "..", "app/src/main/java/com/abyssal/files/MolangData.kt")


def get(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read().decode("utf-8")


def clean(s, limit=160):
    s = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", s)  # links
    s = s.replace("`", "").replace("_e_", "e").replace("\\|", "|").strip()
    s = re.sub(r"\s+", " ", s)
    if len(s) > limit:
        cut = s[:limit]
        s = cut[: cut.rfind(" ")] + "…"
    return s


def query_page(name):
    """(args, deprecated) from the query's own page: args come from the first sample that calls it."""
    try:
        md = get(BASE + "QueryFunctions/query_" + name + ".md")
    except Exception:
        return None, False
    deprecated = "deprecated" in md.lower()
    for m in re.finditer(r"(?:query|q)\." + re.escape(name) + r"\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)", md):
        args = m.group(1).strip()
        if args:
            return args.replace('"', "'"), deprecated
    return None, deprecated


BC = "https://raw.githubusercontent.com/Blockception/BC-Minecraft-Molang/main/src/data/general.ts"
TAKES_ARGS = re.compile(r"\b(takes|argument|arguments|parameter|parameters|specified|given|input)\b", re.I)


def blockception():
    """id -> (parameter names, deprecated) for queries."""
    ts = get(BC)
    ts = ts[ts.index("export const Queries"):]
    out = {}
    for block in re.split(r"\n    \{", ts)[1:]:
        m = re.search(r'id:\s*"(\w+)"', block)
        if not m:
            continue
        params = re.findall(r'\{\s*id:\s*"([^"]+)"', block[m.end():])
        out[m.group(1)] = ([p.strip() for p in params], "deprecated:" in block)
    return out


def kstr(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def main():
    rows = re.findall(r"^\| \[query\.(\w+)\]\([^)]*\)\|\s*(.*?)\s*\|\s*$", get(BASE + "QueryFunctions.md"), re.M)
    with concurrent.futures.ThreadPoolExecutor(16) as ex:
        pages = dict(zip([n for n, _ in rows], ex.map(query_page, [n for n, _ in rows])))
    bc = blockception()
    maths = re.findall(r"^\| \[math\.(\w+)\(([^)]*)\)\]\([^)]*\)\|\s*(.*?)\s*\|\s*$", get(BASE + "MathFunctions.md"), re.M)

    out = [
        "package com.abyssal.files",
        "",
        "// Generated by tools/gen_molang.py from Microsoft's Molang reference (MicrosoftDocs/minecraft-creator) and",
        "// Blockception/BC-Minecraft-Molang (BSD-3-Clause, Copyright (c) 2021, Blockception Ltd). Do not edit by hand.",
        "",
        "internal object MolangData {",
        "    /** name, arguments (null = none), description, deprecated */",
        "    val QUERIES: List<MolangFn> = listOf(",
    ]
    known = {n for n, _ in rows}
    rows += [(n, "") for n in sorted(bc) if n not in known]
    for name, desc in rows:
        args, dep = pages.get(name) or (None, False)
        params, bdep = bc.get(name, ([], False))
        dep = dep or bdep or "deprecated" in desc.lower()
        if not args and params:
            args = ", ".join("equipment slot" if p.startswith("quipment") else p for p in params)
        if not args and TAKES_ARGS.search(desc):
            args = "…"
        if not desc:
            desc = "Deprecated." if dep else ""
        out.append(f"        MolangFn({kstr(name)}, {kstr(args) if args else 'null'}, {kstr(clean(desc))}, {str(dep).lower()}),")
    out += ["    )", "", "    val MATH: List<MolangFn> = listOf("]
    for name, args, desc in maths:
        out.append(f"        MolangFn({kstr(name)}, {kstr(args.strip()) if args.strip() else 'null'}, {kstr(clean(desc))}, false),")
    out += ["    )", "}", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"{len(rows)} queries, {len(maths)} math functions -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
